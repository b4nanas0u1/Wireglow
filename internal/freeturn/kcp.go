package freeturn

// KCPSettings задаёт надёжную доставку TCP-потока поверх датаграмм FreeTurn.
type KCPSettings struct {
	// NoDelay выбирает обычный режим KCP (0) или быстрый режим повторных отправок (1).
	NoDelay int
	// Interval задаёт интервал внутреннего цикла KCP в миллисекундах.
	// Он влияет на частоту обработки подтверждений и повторных отправок.
	Interval int
	// Resend задаёт порог подтверждений более поздних сегментов для быстрой повторной отправки пропущенного сегмента.
	// Ноль отключает быструю повторную отправку.
	Resend int
	// NC управляет контролем перегрузки KCP: 0 включает его, 1 отключает.
	NC int
	// SndWnd задаёт окно отправки в сегментах: сколько данных может ожидать подтверждения.
	SndWnd int
	// RcvWnd задаёт окно приёма в сегментах: сколько данных получатель может буферизовать.
	RcvWnd int
	// MTU задаёт максимальный размер датаграммы KCP в байтах, включая заголовок KCP.
	// Внешние заголовки DTLS, обфускации и TURN в этот размер не входят.
	MTU int
	// ACKNoDelay включает немедленную отправку подтверждений приёма.
	// Это снижает задержку ценой более частых служебных пакетов.
	ACKNoDelay bool
}
